-- Freshness: hours since most recent record
CREATE OR REPLACE DATA METRIC FUNCTION FRESHNESS_HOURS(
  ARG_T TABLE(LAST_UPDATED TIMESTAMP_NTZ)
)
RETURNS NUMBER
COMMENT = 'Returns hours since the most recent record was loaded'
AS
$$
  SELECT COALESCE(DATEDIFF(hour, MAX(LAST_UPDATED), CURRENT_TIMESTAMP()), -1) FROM ARG_T
$$;

-- Completeness: percentage of non-null values
CREATE OR REPLACE DATA METRIC FUNCTION COMPLETENESS_PCT(
  ARG_T TABLE(COL VARCHAR)
)
RETURNS NUMBER
COMMENT = 'Returns percentage of non-null values (0-100)'
AS
$$
  SELECT ROUND(COUNT(COL) * 100.0 / NULLIF(COUNT(*), 0), 1) FROM ARG_T
$$;

-- Out of range count for numeric validation
CREATE OR REPLACE DATA METRIC FUNCTION OUT_OF_RANGE_COUNT(
  ARG_T TABLE(COL NUMBER)
)
RETURNS NUMBER
COMMENT = 'Returns count of values outside expected range (negative values)'
AS
$$
  SELECT COUNT(*) FROM ARG_T WHERE COL < 0
$$;

