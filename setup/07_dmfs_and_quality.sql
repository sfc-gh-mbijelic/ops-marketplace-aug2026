-- ============================================================
-- QUALITY ALERT
-- ============================================================
CREATE OR REPLACE ALERT QUALITY_ALERT
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 0 7 * * * America/Toronto'
  IF (EXISTS (
    SELECT 1
    FROM SNOWFLAKE.LOCAL.DATA_QUALITY_MONITORING_RESULTS
    WHERE TABLE_DATABASE = 'ON_GOVERNANCE_RFS'
      AND METRIC_NAME = 'NULL_COUNT'
      AND VALUE > 100
      AND MEASUREMENT_TIME > DATEADD(hour, -25, CURRENT_TIMESTAMP())
  ))
  THEN
    CALL SYSTEM$SEND_EMAIL(
      'ops_governance_notifications',
      'data-stewards@ontario.ca',
      'OPS Data Quality Alert: High Null Count Detected',
      'One or more governed tables in ON_GOVERNANCE_RFS have exceeded the null count threshold. Review the Governance Console.'
    );

ALTER ALERT QUALITY_ALERT RESUME;

-- ============================================================
-- QUALITY SCORECARD VIEW
-- ============================================================
CREATE OR REPLACE VIEW QUALITY_SCORECARD AS
SELECT
  TABLE_SCHEMA,
  TABLE_NAME,
  MAX(CASE WHEN METRIC_NAME = 'NULL_COUNT' THEN VALUE END) AS NULL_COUNT,
  MAX(CASE WHEN METRIC_NAME = 'DUPLICATE_COUNT' THEN VALUE END) AS DUPLICATE_COUNT,
  MAX(CASE WHEN METRIC_NAME = 'FRESHNESS_HOURS' THEN VALUE END) AS FRESHNESS_HOURS,
  MAX(MEASUREMENT_TIME) AS LAST_MEASURED,
  CASE
    WHEN MAX(CASE WHEN METRIC_NAME = 'NULL_COUNT' THEN VALUE END) = 0
     AND COALESCE(MAX(CASE WHEN METRIC_NAME = 'DUPLICATE_COUNT' THEN VALUE END), 0) = 0
    THEN 'HEALTHY'
    WHEN MAX(CASE WHEN METRIC_NAME = 'NULL_COUNT' THEN VALUE END) > 100
    THEN 'CRITICAL'
    WHEN MAX(CASE WHEN METRIC_NAME = 'NULL_COUNT' THEN VALUE END) > 10
    THEN 'WARNING'
    ELSE 'HEALTHY'
  END AS STATUS,
  -- Trust Score: 0-100 composite
  GREATEST(0, LEAST(100,
    100
    - COALESCE(MAX(CASE WHEN METRIC_NAME = 'NULL_COUNT' THEN VALUE END), 0) * 0.1
    - COALESCE(MAX(CASE WHEN METRIC_NAME = 'DUPLICATE_COUNT' THEN VALUE END), 0) * 0.5
    - CASE WHEN COALESCE(MAX(CASE WHEN METRIC_NAME = 'FRESHNESS_HOURS' THEN VALUE END), 0) > 48 THEN 10 ELSE 0 END
  )) AS TRUST_SCORE
FROM SNOWFLAKE.LOCAL.DATA_QUALITY_MONITORING_RESULTS
WHERE TABLE_DATABASE = 'ON_GOVERNANCE_RFS'
  AND MEASUREMENT_TIME > DATEADD(day, -7, CURRENT_TIMESTAMP())
GROUP BY TABLE_SCHEMA, TABLE_NAME
ORDER BY TABLE_SCHEMA, TABLE_NAME;
